export const modules: Module[] = specs.map((s, i) => ({
  id: i + 1,
  title: s[0],
  subtitle: s[1],
  level: s[2],
  path: s[3],
  resource: s[4],
  prerequisites:
    i === 0 ? [] : i === 1 ? [1] : i === 11 ? [2, 3, 4, 6, 7] : [1, 2],
  lessons: s[5].map((r, j) => ({
    id: `${i + 1}-${j + 1}`,
    title: r[0],
    term: r[1],
    theory: r[2],
    example: r[3],
    practice: r[4],
    mistake: r[5],
  })),
  questions: [
    ...s[5].map((_, j) => {
      const r = appliedQuestions[i * 6 + j];
      return {
        id: `q${i + 1}-${j}`,
        prompt: r[0],
        options: r[1].split("|"),
        correct: r[2].split(",").map(Number),
        explanation: r[3],
        type: "single" as const,
      };
    }),
    ...s[6].map((r, j) => ({
      id: `q${i + 1}-${j + 6}`,
      prompt: r[0],
      options: r[1].split("|"),
      correct: r[2].split(",").map(Number),
      explanation: r[3],
      type: (r[2].includes(",")
        ? "multiple"
        : r[1] === "Да|Нет"
          ? "boolean"
          : "single") as Question["type"],
    })),
  ],
}));
